/**
 * gen-defaults.mjs — 从上游 anzhiyu 主题的 _config.yml 生成 src/config/defaults.ts。
 *
 * 用法：
 *   node scripts/gen-defaults.mjs [configPath]
 *   或 THEME_UPSTREAM_CONFIG=<path> node scripts/gen-defaults.mjs
 *
 * 说明：
 *   - 读取整份 YAML 文档的全部顶层 key（不做白名单/黑名单过滤）。
 *   - 值用 JSON 序列化，数字/布尔/null 原样保留，层级结构保持不变。
 *   - 不手改生成物：需要改默认值就改上游 _config.yml 后重跑本脚本。
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const HERE = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(HERE, '..');
const DEFAULT_UPSTREAM = resolve(
  PKG_ROOT,
  '../../../_research/anzhiyu-upstream/_config.yml',
);

const configPath = resolve(
  process.argv[2] ?? process.env.THEME_UPSTREAM_CONFIG ?? DEFAULT_UPSTREAM,
);
const outPath = resolve(PKG_ROOT, 'src/config/defaults.ts');

const raw = readFileSync(configPath, 'utf8');
const doc = parse(raw);
if (doc === null || typeof doc !== 'object' || Array.isArray(doc)) {
  throw new Error(`[gen-defaults] ${configPath} 顶层不是 YAML mapping`);
}

const topLevelKeys = Object.keys(doc);
const json = JSON.stringify(doc, null, 2);

const banner = `/**
 * AUTO-GENERATED by packages/astro-theme-anzhiyu/scripts/gen-defaults.mjs — DO NOT EDIT.
 *
 * Source: ${configPath.replaceAll('\\', '/')}
 * Top-level keys: ${topLevelKeys.length}
 */

`;

const body = `${banner}export const defaults = ${json} as const;

export type ThemeDefaults = typeof defaults;

export default defaults;
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, body, 'utf8');

const lineCount = body.split('\n').length;
console.log(`[gen-defaults] source: ${configPath}`);
console.log(`[gen-defaults] output: ${outPath}`);
console.log(`[gen-defaults] top-level keys: ${topLevelKeys.length}`);
console.log(`[gen-defaults] bytes: ${Buffer.byteLength(body, 'utf8')}, lines: ${lineCount}`);
